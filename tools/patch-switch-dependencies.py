#!/usr/bin/env python3
"""Apply small, pinned compatibility patches to the Switch-only Lime/OpenFL forks.

These edits are applied to the checked-out Haxelib dependencies in the CI
workspace. They do not modify the upstream desktop dependency set.
"""
import os
from pathlib import Path


def replace_once(path: Path, old: str, new: str, label: str) -> None:
    if not path.is_file():
        raise SystemExit(f"Missing dependency file for {label}: {path}")
    content = path.read_text(encoding="utf-8")
    if new in content:
        print(f"Already patched: {label}")
        return
    if old not in content:
        raise SystemExit(f"Expected source block not found for {label}: {path}")
    path.write_text(content.replace(old, new, 1), encoding="utf-8")
    print(f"Patched: {label}")


root = Path.cwd()
replace_once(
    root / ".haxelib/openfl/git/src/openfl/display/Application.hx",
    "\t\tsuper(appMeta);",
    "\t\tsuper();",
    "OpenFL Application constructor",
)
replace_once(
    root / ".haxelib/openfl/git/src/openfl/sensors/DeviceRotation.hx",
    "\t\t\t#if lime\n\t\t\tvar sensors = Sensor.getSensors(SensorType.GYROSCOPE);",
    "\t\t\t#if (lime && !switch)\n\t\t\tvar sensors = Sensor.getSensors(SensorType.GYROSCOPE);",
    "disable unsupported gyroscope API on Switch",
)
lime_system = root / ".haxelib/lime/git/src/lime/system/System.hx"
if not lime_system.is_file():
    raise SystemExit(f"Missing dependency file for Lime System.setHint: {lime_system}")
lime_content = lime_system.read_text(encoding="utf-8")
if "function setHint(" in lime_content:
    print("Already supported: Lime System.setHint")
else:
    replace_once(
        lime_system,
        "\tpublic static function getTimer():Int",
        "\t/**\n\t * Compatibility stub for orientation hints generated by OpenFL.\n\t * SDL mobile orientation hints do not apply to Nintendo Switch.\n\t */\n\tpublic static function setHint(name:String, value:String):Void {}\n\n\tpublic static function getTimer():Int",
        "Lime System.setHint compatibility",
    )

# Lime-NX's older pinned Switch branch reads playback time with AL_SEC_OFFSET.
# The newer Lime-NX backend uses AL_BYTE_OFFSET for non-streamed buffers instead;
# this avoids a stale/unsupported seconds-offset query on the Switch OpenAL path.
# Keep the calculation equivalent to AudioSource.getLength(), including offsets.
lime_audio_source = root / ".haxelib/lime/git/src/lime/_internal/backend/native/NativeAudioSource.hx"
old_audio_clock = """\t\t\tvar time = (AL.getSourcef(handle, AL.SEC_OFFSET) * 1000.0) - parent.offset;

\t\t\treturn time < 0 ? 0 : time;"""
new_audio_clock = """\t\t\t// BYTE_OFFSET is more reliable than SEC_OFFSET on the Switch OpenAL
\t\t\t// backend for static buffers. Convert the byte position to milliseconds.
\t\t\tif (dataLength <= 0 || parent.buffer.sampleRate <= 0) return 0;

\t\t\tvar byteOffset = AL.getSourcei(handle, AL.BYTE_OFFSET);
\t\t\tvar bytesPerFrame = parent.buffer.channels * (parent.buffer.bitsPerSample / 8.0);
\t\t\tif (bytesPerFrame <= 0) return 0;

\t\t\tvar totalFrames = dataLength / bytesPerFrame;
\t\t\tvar totalSeconds = totalFrames / parent.buffer.sampleRate;
\t\t\tvar ratio = byteOffset / dataLength;
\t\t\tvar time = (totalSeconds * ratio * 1000.0) - parent.offset;

\t\t\treturn time < 0 ? 0 : time;"""
replace_once(
    lime_audio_source,
    old_audio_clock,
    new_audio_clock,
    "Lime Switch OpenAL playback clock (BYTE_OFFSET)",
)

# Use the same byte-based position when seeking. Mixing BYTE_OFFSET reads with
# SEC_OFFSET writes leaves the source position dependent on the unreliable
# seconds-offset query we are trying to avoid.
replace_once(
    lime_audio_source,
    "\tprivate var playing:Bool;",
    "\tprivate var playing:Bool;\n\tprivate var lastByteOffset:Int = 0;\n\tprivate var recoveryCheckpoint:Int = -1;",
    "Lime Switch OpenAL last known playback offset",
)
replace_once(
    lime_audio_source,
    "\t\t\tAL.sourcef(handle, AL.SEC_OFFSET, (value + parent.offset) / 1000.0);",
    """\t\t\tvar bytesPerFrame = parent.buffer.channels * (parent.buffer.bitsPerSample / 8.0);
\t\t\tif (dataLength > 0 && bytesPerFrame > 0 && parent.buffer.sampleRate > 0)
\t\t\t{
\t\t\t\tvar totalSeconds = (dataLength / bytesPerFrame) / parent.buffer.sampleRate;
\t\t\t\tvar secondOffset = (value + parent.offset) / 1000.0;
\t\t\t\tif (secondOffset < 0) secondOffset = 0;
\t\t\t\tif (secondOffset > totalSeconds) secondOffset = totalSeconds;
\t\t\t\tvar totalOffset = Std.int(dataLength * (secondOffset / totalSeconds));
\t\t\t\tAL.sourcei(handle, AL.BYTE_OFFSET, totalOffset);
\t\t\t\tlastByteOffset = totalOffset;
\t\t\t}""",
    "Lime Switch OpenAL byte-based seeking",
)
replace_once(
    lime_audio_source,
    """\tprivate function checkPlay(_):Void
\t{
\t\tif (AL.getSourcei(handle, AL.SOURCE_STATE) == AL.PLAYING)
\t\t{
\t\t\treturn;
\t\t}

\t\tif (loops > 0)
\t\t{
\t\t\tplaying = false;
\t\t\tloops--;
\t\t\tsetCurrentTime(0);
\t\t\tplay();
\t\t\treturn;
\t\t}

\t\tif (!completed)
\t\t{
\t\t\tstop();
\t\t\tparent.onComplete.dispatch();
\t\t}

\t\tcompleted = true;
\t}""",
    """\tprivate function checkPlay(_):Void
\t{
\t\tif (handle == null || !playing) return;

\t\tvar sourceState = AL.getSourcei(handle, AL.SOURCE_STATE);
\t\tif (sourceState == AL.PLAYING)
\t\t{
\t\t\tvar byteOffset = AL.getSourcei(handle, AL.BYTE_OFFSET);
\t\t\tvar bytesPerFrame = parent.buffer.channels * (parent.buffer.bitsPerSample / 8.0);
\t\t\tvar recoveryProgressBytes = Std.int(parent.buffer.sampleRate * bytesPerFrame * 0.25);
\t\t\tif (byteOffset > lastByteOffset)
\t\t\t{
\t\t\t\tlastByteOffset = byteOffset;
\t\t\t\t// Only clear a recovery checkpoint after at least 250 ms of progress.
\t\t\t\tif (recoveryCheckpoint >= 0 && byteOffset >= recoveryCheckpoint + recoveryProgressBytes)
\t\t\t\t{
\t\t\t\t\trecoveryCheckpoint = -1;
\t\t\t\t}
\t\t\t}
\t\t\treturn;
\t\t}

\t\t// A paused source is intentional. Only recover an actually stopped source.
\t\tif (sourceState != AL.STOPPED) return;

\t\t// Resume from the last observed byte position, but do not repeatedly
\t\t// restart at a position where the previous recovery made no progress.
\t\tvar bytesPerFrame = parent.buffer.channels * (parent.buffer.bitsPerSample / 8.0);
\t\tvar finalFrameOffset = dataLength - Std.int(bytesPerFrame);
\t\tvar byteOffset = AL.getSourcei(handle, AL.BYTE_OFFSET);
\t\tvar resumeOffset = byteOffset > lastByteOffset ? byteOffset : lastByteOffset;
\t\tvar recoveryProgressBytes = Std.int(parent.buffer.sampleRate * bytesPerFrame * 0.25);
\t\tvar repeatedStall = recoveryCheckpoint >= 0 && resumeOffset <= recoveryCheckpoint + recoveryProgressBytes;
\t\tif (!repeatedStall && bytesPerFrame > 0 && resumeOffset < finalFrameOffset)
\t\t{
\t\t\trecoveryCheckpoint = resumeOffset;
\t\t\tlastByteOffset = resumeOffset;
\t\t\tAL.sourcei(handle, AL.BYTE_OFFSET, resumeOffset);
\t\t\tAL.sourcePlay(handle);
\t\t\treturn;
\t\t}

\t\t// If a recovery cannot advance the source, don't fall back to looping
\t\t// the same section from the beginning.
\t\tif (repeatedStall) loops = 0;

\t\tif (loops > 0)
\t\t{
\t\t\tplaying = false;
\t\t\tloops--;
\t\t\tsetCurrentTime(0);
\t\t\tplay();
\t\t\treturn;
\t\t}

\t\tif (!completed)
\t\t{
\t\t\tstop();
\t\t\tparent.onComplete.dispatch();
\t\t}

\t\tcompleted = true;
\t}""",
    "Lime Switch OpenAL stopped-source recovery",
)

# SDL's Linux host build enables BSD string helpers in SDL_build_config.h.
# The Lime fork's Linux linker block must explicitly link libbsd for those
# symbols; merely installing libbsd-dev does not add it to the link command.
lime_build = root / ".haxelib/lime/git/project/Build.xml"
old_link = "\t\t\t\t<lib name=\"-lrt\" />\n\t\t\t\t<lib name='-ludev' />"
new_link = old_link + "\n\t\t\t\t<lib name=\"-lbsd\" />"
replace_once(
    lime_build,
    old_link,
    new_link,
    "Lime Linux libbsd link",
)

# Fix an extra closing parenthesis in the pinned HxSwitchVideo Switch backend.
# The upstream expression otherwise prevents Haxe from parsing the dependency.
replace_once(
    root / ".haxelib/hxswitchvideo/git/switchvideo/SwitchVideo.hx",
    'renderPtr = SwitchVideoBackend.switchvideo_mpv_render_context_create(mpvPtr, untyped __cpp__("&{0}", err)));',
    'renderPtr = SwitchVideoBackend.switchvideo_mpv_render_context_create(mpvPtr, untyped __cpp__("&{0}", err));',
    "HxSwitchVideo render-context syntax",
)

# HxSwitchVideo currently accepts an MPV options array but only consumes the
# loop sentinel. Forward its remaining key=value entries to MPV so Switch
# cutscenes can respect the game's subtitle and language preferences.
replace_once(
    root / ".haxelib/hxswitchvideo/git/switchvideo/SwitchVideo.hx",
    "\t\t\tMpv.mpv_set_property_string(mpvPtr, 'keepaspect', 'no');\n\n\t\t\tif (_shouldLoop)",
    "\t\t\tMpv.mpv_set_property_string(mpvPtr, 'keepaspect', 'no');\n\n"
    "\t\t\t// Apply caller-supplied MPV options before initialization.\n"
    "\t\t\tif (options != null)\n"
    "\t\t\t{\n"
    "\t\t\t\tfor (option in options)\n"
    "\t\t\t\t{\n"
    "\t\t\t\t\tfinal separator:Int = option.indexOf('=');\n"
    "\t\t\t\t\tif (separator <= 0) continue;\n"
    "\t\t\t\t\tfinal name:String = option.substring(0, separator);\n"
    "\t\t\t\t\tif (name == 'input-repeat') continue;\n"
    "\t\t\t\t\tfinal value:String = option.substring(separator + 1);\n"
    "\t\t\t\t\tMpv.mpv_set_option_string(mpvPtr, name, value);\n"
    "\t\t\t\t}\n"
    "\t\t\t}\n\n"
    "\t\t\tif (_shouldLoop)",
    "HxSwitchVideo MPV option forwarding",
)

# libmpv is packaged with SDL2 video, audio, and gamepad backends enabled.
# Lime's Switch NRO template links SDL3 but must also link MPV's SDL2 archive.
# Resolve the installed archives now and use absolute paths in LIBS. This avoids
# relying on LIBPATHS surviving Lime's nested Make invocation.
devkitpro = Path(os.environ.get("DEVKITPRO", "/opt/devkitpro"))


def find_switch_archive(filename: str, package: str) -> Path:
    # Do not assume a fixed portlibs layout: devkitPro package revisions may
    # install portlibs in a versioned or package-specific subdirectory.
    matches = sorted(
        path for path in devkitpro.rglob(filename) if path.is_file()
    )
    if not matches:
        raise SystemExit(
            f"Could not locate {filename} from installed package {package} "
            "under "
            f"{devkitpro}. Check the package file list with dkp-pacman -Ql "
            f"{package}."
        )
    # Prefer the standard Switch portlibs tree when more than one copy exists.
    matches.sort(
        key=lambda path: (
            "portlibs/switch" not in path.as_posix(),
            len(path.parts),
            path.as_posix(),
        )
    )
    archive = matches[0].resolve()
    print(
        f"Resolved {package} linker input: {archive} "
        f"({archive.stat().st_size} bytes)"
    )
    if len(matches) > 1:
        print(
            f"Other {filename} candidates: "
            + ", ".join(str(path) for path in matches[1:])
        )
    return archive


mpv_archive = find_switch_archive("libmpv.a", "switch-libmpv")
sdl2_archive = find_switch_archive("libSDL2.a", "switch-sdl2")

switch_makefile = root / ".haxelib/lime/git/templates/switch/MakeFileNRO"
replace_once(
    switch_makefile,
    'export LIBPATHS\t:=\t$(foreach dir,$(LIBDIRS),-L$(dir)/lib)',
    'export LIBPATHS\t:=\t$(foreach dir,$(LIBDIRS),-L$(dir)/lib) -L$(DEVKITPRO)/portlibs/switch/lib',
    "Lime Switch portlibs LIBPATHS",
)
replace_once(
    switch_makefile,
    "        -lmpv -lplacebo",
    f"        {mpv_archive} -lplacebo",
    "Lime Switch MPV absolute archive link",
)
replace_once(
    switch_makefile,
    "-lvorbisfile -lcurl -lvorbis -logg -lSDL3 -lharfbuzz \\\n",
    f"-lvorbisfile -lcurl -lvorbis -logg -lSDL3 {sdl2_archive} -lharfbuzz \\\n",
    "Lime Switch SDL2 absolute archive link required by MPV",
)
